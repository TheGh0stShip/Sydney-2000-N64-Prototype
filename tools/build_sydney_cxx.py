#!/usr/bin/env python3
"""Build Sydney 2000 C++ with GCC 2.8.1 and the SN Systems assembler.

The overlay C++ was generated by a GCC 2.8.1 front end but carries the object
format and assembler expansion produced by SN's N64 tools.  N64 Decomp Kit's
custom pipeline calls this wrapper with a private source and output path.
"""

from __future__ import annotations

import argparse
import os
from pathlib import Path
import shutil
import subprocess


def run(argv: list[str], cwd: Path) -> None:
    subprocess.run(argv, cwd=cwd, check=True)


def find_toolchains() -> tuple[Path, Path]:
    root = Path(os.environ.get("N64DK_TOOLCHAIN", ".toolchain")).resolve()
    sn_candidates = (root / "sn-gcc-2.8", root / "gcc2.8.1sn")
    pm_candidates = (root / "gcc2.8.1pm", root.parent / "gcc2.8.1pm")
    sn = next((path for path in sn_candidates if (path / "asn64.exe").is_file()), None)
    pm = next((path for path in pm_candidates if (path / "cc1plus").is_file()), None)
    if sn is None or pm is None:
        raise SystemExit(
            "Sydney C++ needs sn-gcc-2.8 (wibo, asn64, psyq-obj-parser) and "
            "gcc2.8.1pm (cc1plus) under N64DK_TOOLCHAIN"
        )
    return sn, pm


def adapt_assembly(path: Path) -> None:
    kept: list[str] = []
    skip = False
    for line in path.read_text(errors="replace").splitlines():
        word = line.strip().split()[0] if line.strip() else ""
        if word == ".section":
            skip = ".eh_frame" in line or ".gcc_except" in line
            if skip:
                continue
            if ".gnu.linkonce." in line:
                kind = line.split(".gnu.linkonce.", 1)[1][:1]
                if kind == "t":
                    skip = True
                    continue
                line = "\t" + {"r": ".rdata"}.get(kind, ".data")
        elif word in (".text", ".data", ".rdata", ".sdata", ".bss"):
            skip = False
        if skip or word in (".version", ".type", ".size"):
            continue
        if word == ".string":
            line = line.replace(".string", ".ascii", 1).rstrip()[:-1] + '\\000"'
        elif word == ".weak":
            line = line.replace(".weak", ".globl", 1)
        elif word == ".comm" and line.count(",") == 2:
            line = line.rsplit(",", 1)[0]
        kept.append(line)
    path.write_bytes(("\r\n".join(kept) + "\r\n").encode())


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--source", type=Path, required=True)
    parser.add_argument("--object", type=Path, required=True)
    parser.add_argument("--workdir", type=Path, required=True)
    parser.add_argument("flags", nargs=argparse.REMAINDER)
    args = parser.parse_args()
    flags = args.flags[1:] if args.flags[:1] == ["--"] else args.flags
    workdir = args.workdir.resolve()
    source = args.source.resolve()
    output = args.object.resolve()
    sn, pm = find_toolchains()
    preprocessed = workdir / f"{source.stem}.i"
    assembly = workdir / f"{source.stem}.s"
    psyq = workdir / f"{source.stem}.obj"
    compiler_flags = [flag for flag in flags if not flag.startswith("-I")]
    includes = [flag for flag in flags if flag.startswith("-I")]
    run([
        shutil.which("gcc") or "gcc", "-E", "-P", "-undef", "-D__GNUC__=2",
        "-D__GNUC_MINOR__=8", *includes, str(source), "-o", str(preprocessed),
    ], workdir)
    run([str(pm / "cc1plus"), "-quiet", *compiler_flags, str(preprocessed), "-o", str(assembly)], workdir)
    adapt_assembly(assembly)
    run([str(sn / "wibo"), str(sn / "asn64.exe"), "-o", str(psyq), str(assembly)], workdir)
    run([str(sn / "psyq-obj-parser"), str(psyq), "-b", "-n", "-o", str(output)], workdir)


if __name__ == "__main__":
    main()
